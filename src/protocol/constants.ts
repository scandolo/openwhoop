export type PacketTypeId = (typeof PacketType)[keyof typeof PacketType];

/** Reverse lookup for logs and the packet inspector. */
export function nameOf(table: Record<string, number>, value: number): string {
  for (const [k, v] of Object.entries(table)) if (v === value) return k;
  return String(value);
}
